"""The cards' copy of the texts (frontend/nibepi-texts.js) and the JS
parity fixture (tests/js/texts-parity.json) match the catalogue: both are
generated by tools/gen_texts_js.py; rerun it after changing a text."""

from __future__ import annotations

import importlib.util
import os
import unittest

import context  # noqa: F401

TOOL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "gen_texts_js.py")


def load_tool():
    spec = importlib.util.spec_from_file_location("gen_texts_js", TOOL)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


class GeneratedTextsTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tool = load_tool()

    def test_committed_files_match_the_catalogue(self) -> None:
        for path, text in self.tool.outputs().items():
            with self.subTest(path=os.path.basename(path)):
                with open(path, encoding="utf-8", newline="") as handle:
                    self.assertEqual(handle.read(), text, "run python3 tools/gen_texts_js.py")

    def test_the_cards_support_every_format_spec(self) -> None:
        self.assertEqual(sorted(set(self.tool.specs()) - set(self.tool.SUPPORTED_SPECS)), [])

    def test_every_code_has_a_parity_case(self) -> None:
        from logic.texts import CATALOGUE

        codes = {case["text"]["c"] for case in self.tool.parity_cases()}
        self.assertEqual(set(CATALOGUE) - codes, set())

    def test_output_is_deterministic(self) -> None:
        self.assertEqual(self.tool.outputs(), load_tool().outputs())


if __name__ == "__main__":
    unittest.main()
