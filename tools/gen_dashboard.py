#!/usr/bin/env python3
"""Write the committed dashboards from logic/dashboard.py.

    python3 tools/gen_dashboard.py           # write dashboards/*.yaml
    python3 tools/gen_dashboard.py --check   # exit 1 when they are stale

The entity ids are Home Assistant's defaults for a fresh install: the
integration's device named "Nibe F1255" (its default name), climate system
S1 only, and the gateway's discovered device "Nibe F1255" with the F1255
register titles. Other names, S2 or a missing gateway sensor: use the
nibepi.get_dashboard action, which finds the real entity ids.
No Home Assistant needed.
"""

from __future__ import annotations

import json
import os
import re
import sys
import unicodedata
from typing import Dict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPONENT = os.path.join(ROOT, "custom_components", "nibepi")
sys.path.insert(0, COMPONENT)

from logic import dashboard  # noqa: E402

DEVICE = "Nibe F1255"
GATEWAY_DEVICE = "Nibe F1255"
SYSTEMS = ("s1",)
# The gateway's register titles (nibepi-backend models/F1255.json).
REGISTER_TITLES = {
    40004: "BT1 Outdoor Temperature",
    40007: "EP21-BT2 Supply temp S2",
    40008: "BT2 Supply temp S1",
    40012: "EB100-EP14-BT3 Return temp",
    40013: "BT7 HW Top",
    40014: "BT6 HW Load",
    40032: "EP21-BT50 Room Temp S2",
    40033: "BT50 Room Temp S1",
    43005: "Degree Minutes (16 bit)",
    43086: "Prio",
    43136: "Compressor Frequency, Actual",
    43141: "compr. in power",
}
# The MQTT sensor in the README's Dashboard section.
BUS_HEALTH = "sensor.nibe_bus_health"

FILES = {
    "dashboards/nibepi.yaml": (
        dashboard.build_dashboard,
        "NibePi dashboard, generated by tools/gen_dashboard.py: do not edit.\n"
        "The entity ids are the defaults of a fresh install (device \"Nibe F1255\", S1).\n"
        "Better: Developer tools -> Actions -> nibepi.get_dashboard returns this\n"
        "dashboard with your entity ids. Paste either into Settings -> Dashboards ->\n"
        "Add dashboard -> menu -> Raw configuration editor. See the README.",
    ),
    "dashboards/nibepi-apexcharts.yaml": (
        dashboard.build_apexcharts,
        "OPTIONAL: needs the apexcharts-card from HACS (not built in).\n"
        "The optimiser's planned offset and predicted indoor temperature for the\n"
        "next 24 h, with the price level. Generated by tools/gen_dashboard.py: do\n"
        "not edit. nibepi.get_dashboard returns it with your entity ids as\n"
        "apexcharts_yaml.",
    ),
}


def slugify(text: str) -> str:
    """Home Assistant's ``util.slugify`` for plain names."""
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def entity_names() -> Dict[str, Dict[str, str]]:
    with open(os.path.join(COMPONENT, "strings.json"), encoding="utf-8") as handle:
        entity = json.load(handle)["entity"]
    return {platform: {key: item["name"] for key, item in keys.items()} for platform, keys in entity.items()}


def default_entity_ids(systems=SYSTEMS) -> Dict[str, str]:
    names = entity_names()

    def entity_id(domain: str, name: str) -> str:
        return "%s.%s" % (domain, slugify("%s %s" % (DEVICE, name)))

    found = {key: entity_id(domain, names[domain][key]) for key, domain in dashboard.SHARED_ENTITIES}
    for system in systems:
        for key, domain in dashboard.SYSTEM_ENTITIES:
            name = names[domain][key].replace("{system}", system.upper())
            found["%s_%s" % (key, system)] = entity_id(domain, name)
    for key, register in dashboard.gateway_registers(systems).items():
        found[key] = "sensor.%s" % slugify("%s %s" % (GATEWAY_DEVICE, REGISTER_TITLES[register]))
    for system in systems:
        found["indoor_" + system] = found["bt50_" + system]
    found["bus_health"] = BUS_HEALTH
    return found


def render() -> Dict[str, str]:
    """Published path -> file content."""
    entities = default_entity_ids()
    return {
        path: dashboard.dump_yaml(build(entities, {"title": "NibePi"}), header)
        for path, (build, header) in FILES.items()
    }


def main(argv) -> int:
    check = "--check" in argv
    stale = []
    for path, text in render().items():
        full = os.path.join(ROOT, path)
        try:
            with open(full, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current == text:
            continue
        stale.append(path)
        if not check:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
    for path in stale:
        print(("stale: " if check else "wrote: ") + path)
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
