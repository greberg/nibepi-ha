"""Generate the cards' copy of the logic's texts from logic/texts.py.

The entities carry their texts as codes and parameters (the ``i18n``
attribute); the cards render them in the viewer's language with the
catalogue in ``frontend/nibepi-texts.js``. A second file,
``tests/js/texts-parity.json``, holds Python's rendering of a sample text
for every code (and some edge cases) in both languages: the JS tests check
that the cards render them the same.

    python3 tools/gen_texts_js.py          # write both files
    python3 tools/gen_texts_js.py --check  # exit 1 when they are out of date

tests/test_texts_js.py fails when the committed files drift from the
catalogue. Output is deterministic (catalogue order, LF, UTF-8).
"""

from __future__ import annotations

import json
import os
import string
import sys
from typing import Any, Dict, List, Tuple

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(ROOT, "custom_components", "nibepi"))

from logic.texts import CATALOGUE, LANGS, Msg, msg, render, structured, term  # noqa: E402

TEXTS_JS = os.path.join(ROOT, "custom_components", "nibepi", "frontend", "nibepi-texts.js")
PARITY_JSON = os.path.join(ROOT, "tests", "js", "texts-parity.json")

# The format specs the cards' renderer supports (nibepi-i18n.js).
SUPPORTED_SPECS = ("", "d", "+d", "g", "+g", ".0f", ".1f", ".2f", "+.1f", "+.2f")

# Sample values, used in turn: ties, negatives, zero, large and small.
NUMBERS = (21.45, -1.25, 0.125, 2.5, -0.004, 1234567.0, 3, 0, 46.05, 0.0001, -7.5, 99.995, 0.35, -0.0, 1e-05, 17)
VALUES: Tuple[Any, ...] = (
    "sensor.indoor",
    term("model_level", "low"),
    msg("explain.price", price=1.5, unit="SEK/kWh", avg=-1.0),
    "06:00",
    msg("opt.no_plan_why", why=msg("price.no_prices_in", entity="sensor.nordpool")),
)


def specs() -> List[str]:
    """Every format spec in the catalogue, sorted."""
    found = set()
    for texts in CATALOGUE.values():
        for text in texts:
            for _literal, name, spec, _conv in string.Formatter().parse(text):
                if name is not None:
                    found.add(spec)
    return sorted(found)


def texts_js() -> str:
    lines = [
        "// Generated by tools/gen_texts_js.py from custom_components/nibepi/logic/texts.py:",
        "// do not edit. The logic's texts, code -> [English, Swedish], for the cards",
        "// to render the entities' i18n attribute in the viewer's language.",
        "",
        "export const TEXT_LANGS = %s;" % json.dumps(list(LANGS)),
        "",
        "export const TEXTS = {",
    ]
    for code, texts in CATALOGUE.items():
        lines.append("  %s: %s," % (json.dumps(code, ensure_ascii=False), json.dumps(list(texts), ensure_ascii=False)))
    lines.append("};")
    return "\n".join(lines) + "\n"


def _sample(code: str, counter: List[int]) -> Msg:
    """``code`` with a parameter for each placeholder, by its spec."""
    params: Dict[str, Any] = {}
    for _literal, name, spec, _conv in string.Formatter().parse(CATALOGUE[code][0]):
        if name is None or name in params:
            continue
        i = counter[0]
        counter[0] += 1
        params[name] = NUMBERS[i % len(NUMBERS)] if spec else VALUES[i % len(VALUES)]
    return Msg(code, params)


def _extra() -> List[Any]:
    """Edge cases besides one sample per code."""
    return [
        msg("away.fixed", offset=-3.0),
        msg("away.fixed", offset=2.0),
        msg("weather.lower_blocked", offset=-0.5),
        msg("opt.plan_old", minutes=90.0),
        msg("opt.plan_old", minutes=-1.9),
        msg("meter.not_found", entity="sensor.meter"),
        msg("price.level", level=term("price_level", "CHEAP"), source=term("price_source", "optimiser")),
        msg("strategy.not_used", reason=msg("gate.low_confidence", level=term("model_level", "low"),
                                            confidence=0.52, min_level=term("model_level", "high"))),
        msg("indoor.ok", setpoint=21.0, indoor=20.25, factor=2.0),
        msg("indoor.ok", setpoint=21.0, indoor=20.35, factor=0.0001),
        msg("indoor.ok", setpoint=21.0, indoor=20.0, factor=123456789.0),
        msg("indoor.ok", setpoint=-0.04, indoor=0.05, factor=-0.0),
        msg("weather.not_covered", hours=1e16),
        msg("weather.raise_blocked", offset=0.125),
        msg("weather.raise_blocked", offset=0.375),
        msg("weather.raise_blocked", offset=0.0),
        msg("gate.floor", floor=9.95),
        msg("gate.floor", floor=0.05),
        # A string where a number is expected: Swedish fails, English too.
        msg("gate.floor", floor="x"),
        # Missing parameters and an unknown code: the code.
        Msg("priority.over", {}),
        Msg("no.such.code", {"a": 1}),
        msg("common.join", first=msg("opt.no_plan"), second="sensor.x"),
    ]


def parity_cases() -> List[Dict[str, Any]]:
    counter = [0]
    cases: List[Dict[str, Any]] = []
    for item in [_sample(code, counter) for code in CATALOGUE] + _extra():
        case: Dict[str, Any] = {"text": structured(item)}
        for lang in LANGS:
            case[lang] = item.render(lang)
        nested = render(item.code, item.params, "sv", nested=True)
        if nested != case["sv"]:
            case["sv_nested"] = nested
        cases.append(case)
    return cases


def parity_json() -> str:
    """One case per line: {"text": structured, "en": ..., "sv": ..., "sv_nested": ...}."""
    rows = [json.dumps(case, ensure_ascii=False) for case in parity_cases()]
    return "[\n" + ",\n".join(rows) + "\n]\n"


def outputs() -> Dict[str, str]:
    return {TEXTS_JS: texts_js(), PARITY_JSON: parity_json()}


def main(argv: List[str]) -> int:
    unsupported = sorted(set(specs()) - set(SUPPORTED_SPECS))
    if unsupported:
        print("format specs the cards cannot render: %s (add them to nibepi-i18n.js)" % unsupported)
        return 1
    stale = []
    for path, text in outputs().items():
        try:
            with open(path, encoding="utf-8", newline="") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if "--check" not in argv:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
    if "--check" in argv and stale:
        print("out of date: %s (run python3 tools/gen_texts_js.py)" % ", ".join(stale))
        return 1
    for path in stale:
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
